/**
 * Parse a CalCentral Academic Summary PDF and generate scripts/profile.mjs.
 *
 * Usage:
 *   node scripts/parse-calcentral.mjs "Academic Summary _ CalCentral.pdf"
 *   node scripts/parse-calcentral.mjs summary.pdf --target fall-2026
 *   node scripts/parse-calcentral.mjs summary.pdf --force
 */

import { execSync } from 'node:child_process'
import { writeFile, access } from 'node:fs/promises'
import {
  extractCoursesFromText,
  semLabel,
  semSort,
} from '../lib/parse-calcentral-core.mjs'

function extractCourses(pdfPath) {
  const raw = execSync(`strings "${pdfPath}"`, { encoding: 'utf8', maxBuffer: 50 * 1024 * 1024 })
  return extractCoursesFromText(raw)
}

function generateProfile(semesters, targetKey) {
  const keys = [...semesters.keys()].sort(semSort)
  const completedKeys = keys.filter(k => k !== targetKey)
  const termsCompleted = completedKeys.length

  const completedLines = []
  for (const key of completedKeys) {
    const courses = semesters.get(key)
    completedLines.push(`  // ${semLabel(key)}`)
    completedLines.push(`  ${courses.map(c => `'${c}'`).join(', ')},`)
  }

  const currentCourses = semesters.get(targetKey) ?? []
  const currentComment = currentCourses.length
    ? `// Current enrollment (${semLabel(targetKey)}): ${currentCourses.join(', ')}`
    : ''

  return `/**
 * Student profile — generated by parse-calcentral.mjs
 * ${currentComment ? currentComment + '\n *' : ''}
 * Review and edit this file before running the build pipeline:
 *   - Add AP/CC/equivalency credits to COMPLETED_BY_EQUIVALENCY
 *   - Fill in your major, college, and degree in PROFILE
 *   - Add prose prerequisite patterns to PROSE_SATISFIED if applicable
 */

export const COMPLETED = [
${completedLines.join('\n')}
]

/**
 * Credit held by equivalency (AP, community college, etc.) rather than by a
 * Berkeley enrollment. Add courses here that you have credit for but didn't
 * take at Berkeley.
 */
export const COMPLETED_BY_EQUIVALENCY = [
  // e.g. 'MATH 1A', 'PHYSICS 7A',
]

export const ALL_COMPLETED = [...COMPLETED, ...COMPLETED_BY_EQUIVALENCY]

/**
 * Prose requirements that the completed record satisfies. These are regex
 * patterns that match prerequisite text like "one year of calculus".
 * Uncomment or add patterns that match your preparation.
 */
export const PROSE_SATISFIED = [
  // /\\b(?:one|1|a)\\s+year\\s+of\\s+calculus\\b/i,
  // /\\btwo\\s+semesters\\s+of\\s+calculus\\b/i,
]

export const PROFILE = {
  major: 'Undeclared', // TODO: your major
  degree: 'BA', // TODO: BA or BS
  college: 'L&S', // TODO: L&S, CDSS, CoE, etc.
  career: 'UGRD',
  isDeclared: false, // TODO: set to true if declared
  isTransfer: false,
  isVisiting: false,
  isMinorOnly: false,
  termsCompleted: ${termsCompleted},
  termsIncludingTarget: ${termsCompleted + 1},
}
`
}

async function main() {
  const args = process.argv.slice(2)
  const flags = args.filter(a => a.startsWith('--'))
  const positional = args.filter(a => !a.startsWith('--'))

  const pdfPath = positional[0]
  if (!pdfPath) {
    console.error('Usage: node scripts/parse-calcentral.mjs <path-to-pdf> [--target fall-2026] [--force]')
    process.exit(1)
  }

  const force = flags.includes('--force')
  const targetIdx = flags.indexOf('--target')
  const targetOverride = targetIdx >= 0 ? flags[targetIdx + 1] ?? args[args.indexOf('--target') + 1] : null

  const semesters = extractCourses(pdfPath)

  if (!semesters.size) {
    console.error('No courses found in the PDF. Is this a CalCentral Academic Summary?')
    process.exit(1)
  }

  const keys = [...semesters.keys()].sort(semSort)
  const targetKey = targetOverride ?? keys[keys.length - 1]

  if (!semesters.has(targetKey) && targetOverride) {
    console.warn(`Warning: --target ${targetOverride} not found in PDF semesters: ${keys.join(', ')}`)
  }

  console.log('Semesters found:')
  for (const key of keys) {
    const label = key === targetKey ? ' ← target (excluded from COMPLETED)' : ''
    console.log(`  ${semLabel(key)}: ${semesters.get(key).join(', ')}${label}`)
  }

  const completedKeys = keys.filter(k => k !== targetKey)
  const totalCompleted = completedKeys.reduce((n, k) => n + semesters.get(k).length, 0)
  console.log(`\n${totalCompleted} completed courses across ${completedKeys.length} terms`)

  const outPath = new URL('profile.mjs', import.meta.url)

  if (!force) {
    try {
      await access(outPath)
      console.error(`\nscripts/profile.mjs already exists. Use --force to overwrite.`)
      process.exit(1)
    } catch {}
  }

  const content = generateProfile(semesters, targetKey)
  await writeFile(outPath, content)
  console.log(`\nWrote scripts/profile.mjs`)
  console.log('Next steps:')
  console.log('  1. Review and edit profile.mjs (major, college, equivalencies)')
  console.log('  2. node scripts/build-dataset.mjs')
  console.log('  3. node scripts/build-page.mjs')
}

main().catch(err => {
  console.error(err)
  process.exit(1)
})
